function css(sheet: FrameSheet): string {
  if (sheet.layout === "tall") return tallFrameCss();
  if (sheet.fit === null)
    throw new Error(`frame-sheets: "${sheet.name}" is fitted but has no fit`);
  return mountedSheetFrameCss(sheet.fit, sheet.hero, sheet.layout);
}

export function frameSheetFile(sheet: FrameSheet): string {
  return `/* Generated by \`npm run frames\` from app/_frame/frame-sheets.ts — DO NOT hand-edit; re-run the script instead. */\n${css(sheet)}\n`;
}
